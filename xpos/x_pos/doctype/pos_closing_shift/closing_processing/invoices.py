import frappe
from erpnext.accounts.doctype.pos_invoice_merge_log.pos_invoice_merge_log import (
	get_invoice_customer_map,
	split_invoices,
)
from frappe.utils import get_time, getdate

from xpos.api.utilities import get_invoice_type


def set_closing_entry_invoices(closing_shift_doc):
	"""Set `pos_closing_entry` on linked invoices."""
	for d in closing_shift_doc.pos_transactions:
		invoice = d.get("sales_invoice") or d.get("pos_invoice")
		if not invoice:
			continue
		doctype = "Sales Invoice" if d.get("sales_invoice") else "POS Invoice"
		if frappe.db.has_column(doctype, "pos_closing_entry"):
			frappe.db.set_value(doctype, invoice, "pos_closing_entry", closing_shift_doc.name)


def clear_closing_entry_invoices(closing_shift_doc):
	"""Clear closing shift links, cancel merge logs and cancel consolidated sales invoices."""
	consolidated_sales_invoices = set()
	for d in closing_shift_doc.pos_transactions:
		pos_invoice = d.get("pos_invoice")
		sales_invoice = d.get("sales_invoice")
		if pos_invoice:
			if frappe.db.has_column("POS Invoice", "pos_closing_entry"):
				frappe.db.set_value("POS Invoice", pos_invoice, "pos_closing_entry", None)

			merge_logs = frappe.get_all(
				"POS Invoice Merge Log",
				filters={"pos_invoice": pos_invoice},
				pluck="name",
			)
			for log in merge_logs:
				log_doc = frappe.get_doc("POS Invoice Merge Log", log)
				for field in (
					"consolidated_invoice",
					"consolidated_credit_note",
				):
					si = log_doc.get(field)
					if si:
						consolidated_sales_invoices.add(si)
				if log_doc.docstatus == 1:
					log_doc.cancel()
				frappe.delete_doc("POS Invoice Merge Log", log_doc.name, force=1)

			if frappe.db.has_column("POS Invoice", "consolidated_invoice"):
				frappe.db.set_value("POS Invoice", pos_invoice, "consolidated_invoice", None)

			if frappe.db.has_column("POS Invoice", "status"):
				pos_doc = frappe.get_doc("POS Invoice", pos_invoice)
				pos_doc.set_status(update=True)

		if sales_invoice:
			if frappe.db.has_column("Sales Invoice", "pos_closing_entry"):
				frappe.db.set_value("Sales Invoice", sales_invoice, "pos_closing_entry", None)
			if is_consolidated_sales_invoice(sales_invoice):
				consolidated_sales_invoices.add(sales_invoice)

	for si in consolidated_sales_invoices:
		if frappe.db.exists("Sales Invoice", si):
			si_doc = frappe.get_doc("Sales Invoice", si)
			if si_doc.docstatus == 1:
				si_doc.cancel()


def is_consolidated_sales_invoice(sales_invoice):
	"""Return True if the Sales Invoice was generated by consolidating POS Invoices."""

	if not sales_invoice:
		return False

	if frappe.db.exists("POS Invoice Merge Log", {"consolidated_invoice": sales_invoice}):
		return True

	return bool(frappe.db.exists("POS Invoice Merge Log", {"consolidated_credit_note": sales_invoice}))


def delete_draft_invoices(pos_opening_shift, pos_profile):
	if not frappe.db.get_value("POS Profile", pos_profile, "allow_delete_draft_invoices"):
		return

	doctype = get_invoice_type()

	invoice_names = frappe.get_all(
		doctype,
		filters={
			"docstatus": 0,
			"is_printed": 0,
			"pos_opening_shift": pos_opening_shift,
		},
		pluck="name",
	)

	for invoice_name in invoice_names:
		frappe.delete_doc(
			doctype,
			invoice_name,
			force=True,
		)


def submit_printed_invoices(pos_opening_shift, doctype):
	invoices_list = frappe.get_all(
		doctype,
		filters={
			"pos_opening_shift": pos_opening_shift,
			"docstatus": 0,
			"is_printed": 1,
		},
	)
	for invoice in invoices_list:
		invoice_doc = frappe.get_doc(doctype, invoice.name)
		invoice_doc.submit()


def consolidate_closing_shift_invoices(closing_shift_doc):
	if get_invoice_type() != "POS Invoice":
		return
	frappe.enqueue(
		run_closing_shift_consolidation,
		queue="long",
		timeout=7200,
		job_id=f"xpos_consolidate::{closing_shift_doc.name}",
		deduplicate=True,
		enqueue_after_commit=True,
		now=frappe.in_test,
		closing_shift=closing_shift_doc.name,
	)


def get_unconsolidated_invoices(closing_shift):
	names = frappe.get_all(
		"Sales Invoice Reference",
		filters={"parenttype": "POS Closing Shift", "parent": closing_shift, "pos_invoice": ["is", "set"]},
		pluck="pos_invoice",
	)
	if not names:
		return []
	return frappe.get_all(
		"POS Invoice",
		filters={
			"name": ["in", names],
			"docstatus": 1,
			"consolidated_invoice": ["in", ["", None]],
		},
		fields=[
			"name as pos_invoice",
			"customer",
			"is_return",
			"return_against",
			"currency",
			"posting_date",
			"posting_time",
		],
		order_by="posting_date asc, posting_time asc, name asc",
	)


def sync_closing_shift_sales_invoices(closing_shift):
	frappe.db.sql(
		"""
		update `tabSales Invoice Reference` r
		join `tabPOS Invoice` p on p.name = r.pos_invoice
		set r.sales_invoice = nullif(p.consolidated_invoice, '')
		where r.parenttype = 'POS Closing Shift'
			and r.parent = %s
			and not (ifnull(r.sales_invoice, '') <=> ifnull(p.consolidated_invoice, ''))
		""",
		closing_shift,
	)


def count_unlinked_closing_rows(closing_shift):
	return frappe.db.sql(
		"""
		select count(*)
		from `tabSales Invoice Reference` r
		join `tabPOS Invoice` p on p.name = r.pos_invoice
		where r.parenttype = 'POS Closing Shift'
			and r.parent = %s
			and not (ifnull(r.sales_invoice, '') <=> ifnull(p.consolidated_invoice, ''))
		""",
		closing_shift,
	)[0][0]


def run_closing_shift_consolidation(closing_shift):
	pos_invoices = get_unconsolidated_invoices(closing_shift)
	if not pos_invoices:
		sync_closing_shift_sales_invoices(closing_shift)
		return

	company = frappe.db.get_value("POS Closing Shift", closing_shift, "company")
	for invoice in pos_invoices:
		if invoice.return_against and not frappe.db.exists("POS Invoice", invoice.return_against):
			invoice.return_against = None

	groups = {}
	for invoice in pos_invoices:
		groups.setdefault((getdate(invoice.posting_date), invoice.currency), []).append(invoice)

	for (posting_date, currency), invoices in sorted(groups.items(), key=lambda g: (g[0][0], g[0][1] or "")):
		posting_time = max(get_time(inv.posting_time or "00:00:00") for inv in invoices)
		try:
			create_dated_merge_logs(invoices, company, posting_date, posting_time)
			sync_closing_shift_sales_invoices(closing_shift)
			frappe.db.commit()
		except Exception:
			frappe.db.rollback()
			frappe.log_error(
				title=f"POS Closing Shift {closing_shift}: invoice consolidation failed for {posting_date}",
				reference_doctype="POS Closing Shift",
				reference_name=closing_shift,
			)
			raise


def create_dated_merge_logs(invoices, company, posting_date, posting_time):
	for customer, invoices_by_dimension in get_invoice_customer_map(invoices).items():
		for dimension_invoices in invoices_by_dimension.values():
			for chunk in split_invoices(dimension_invoices):
				merge_log = frappe.new_doc("POS Invoice Merge Log")
				merge_log.posting_date = posting_date
				merge_log.posting_time = posting_time
				merge_log.company = company
				merge_log.customer = customer
				merge_log.set("pos_invoices", chunk)
				merge_log.save(ignore_permissions=True)
				merge_log.submit()
